"use strict";
const {test}=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const {chromium}=require("playwright");
const URL_BASE=process.env.UNIVERSAL_BOX_UI_URL||"http://127.0.0.1:1420/";
const target=path.join(__dirname,"browser-test-results","smart-command-palette");
fs.mkdirSync(target,{recursive:true});
test("Existing Cmd+K palette supports Chinese task search, per-tool pins, local recents and keyboard selection",{timeout:75000},async()=>{
 const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 try{
  await page.goto(URL_BASE,{waitUntil:"domcontentloaded"});await page.locator(".app-shell").waitFor();
  await page.keyboard.press("Control+k");
  const input=page.locator('[data-testid="palette-search"]');await input.waitFor();
  assert.equal(await input.getAttribute("role"),"combobox");
  await input.fill("发票");
  await page.locator('[data-testid="palette-result"]').first().waitFor();
  assert.match(await page.locator('[data-testid="palette-result"]').first().innerText(),/Invoices & Quotes/);
  await page.locator('[data-testid="palette-pin"]').first().click();
  assert.equal(await page.locator('[data-testid="palette-pin"]').first().getAttribute("aria-pressed"),"true");
  await page.keyboard.press("Escape");
  await page.keyboard.press("Control+k");
  await input.waitFor();
  const first=await page.locator('[data-testid="palette-result"]').first().innerText();
  assert.match(first,/Business Invoices & Quotes/,"Pinned business workflow must be first in empty palette");
  await page.keyboard.press("Enter");
  await page.locator('[data-testid="business-billing-desk"]').waitFor();
  await page.keyboard.press("Control+k");
  const again=page.locator('[data-testid="palette-search"]');await again.waitFor();
  await again.fill("压缩pdf");
  const options=page.locator('[data-testid="palette-result"]');
  assert.equal(await options.count(),2,"Two distinct real PDF compression modes must be searchable");
  assert.match(await options.first().innerText(),/Scanned PDF/);
  await again.press("ArrowDown");
  assert.equal(await options.nth(1).getAttribute("aria-selected"),"true");
  await again.press("Enter");
  const activeTab=page.locator('[aria-label="PDF mini editor modes"] .active-pill');
  await activeTab.waitFor();
  assert.match(await activeTab.innerText(),/Compress PDF/);
  await page.keyboard.press("Control+k");
  await page.locator('[data-testid="palette-search"]').fill("");
  assert.match(await page.locator('[data-testid="palette-result"]').first().innerText(),/Business Invoices & Quotes/);
  await page.screenshot({path:path.join(target,"palette-pinned-recent.png"),fullPage:true});
  await page.reload({waitUntil:"domcontentloaded"});
  await page.locator(".app-shell").waitFor();
  await page.keyboard.press("Control+k");
  assert.match(await page.locator('[data-testid="palette-result"]').first().innerText(),/Business Invoices & Quotes/);
  assert.equal(await page.locator('[data-testid="palette-pin"]').first().getAttribute("aria-pressed"),"true");
  assert.deepEqual(errors,[]);
 }finally{await page.close();await browser.close();}
});
